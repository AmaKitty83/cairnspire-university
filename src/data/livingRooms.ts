export function pointInPolygon(
  pt: { x: number; y: number },
  poly: Array<{ x: number; y: number }>
): boolean {
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const xi = poly[i].x;
    const yi = poly[i].y;
    const xj = poly[j].x;
    const yj = poly[j].y;
    const intersect =
      yi > pt.y !== yj > pt.y &&
      pt.x < ((xj - xi) * (pt.y - yi)) / (yj - yi || 1e-6) + xi;
    if (intersect) inside = !inside;
  }
  return inside;
}

export function clampPointToPolygon(
  pt: { x: number; y: number },
  poly: Array<{ x: number; y: number }>
): { x: number; y: number } {
  if (poly.length === 0 || pointInPolygon(pt, poly)) return pt;
  let best = poly[0];
  let bestDistSq = Infinity;
  for (let i = 0; i < poly.length; i++) {
    const a = poly[i];
    const b = poly[(i + 1) % poly.length];
    const dx = b.x - a.x;
    const dy = b.y - a.y;
    const lenSq = dx * dx + dy * dy || 1;
    const t = Math.max(0, Math.min(1, ((pt.x - a.x) * dx + (pt.y - a.y) * dy) / lenSq));
    const proj = { x: a.x + t * dx, y: a.y + t * dy };
    const distSq = (pt.x - proj.x) ** 2 + (pt.y - proj.y) ** 2;
    if (distSq < bestDistSq) {
      bestDistSq = distSq;
      best = proj;
    }
  }
  return best;
}

const DEFAULT_PROP_WIDTH: Record<IsometricPropDef['kind'], number> = {
  'iso-chair': 44,
  'iso-stool': 38,
  'iso-command-desk': 88,
  'iso-lockout-console': 80,
  'iso-checkpoint': 56,
  painted: 82,
};

function getPropEllipse(prop: IsometricPropDef) {
  const w = prop.width ?? DEFAULT_PROP_WIDTH[prop.kind] ?? 82;
  return {
    cx: prop.x,
    cy: prop.y + 4,
    rx: Math.max(12, w * 0.42),
    ry: Math.max(6, w * 0.17),
  };
}

/** True when a point falls inside a non-walkable prop's ground collision ellipse. */
export function isPointInPropObstacle(
  pt: { x: number; y: number },
  prop: IsometricPropDef,
  scale = 1
): boolean {
  if (prop.walkable) return false;
  const { cx, cy, rx, ry } = getPropEllipse(prop);
  const nx = (pt.x - cx) / (rx * scale);
  const ny = (pt.y - cy) / (ry * scale);
  return nx * nx + ny * ny < 1;
}

/** Clamp a clicked floor coordinate inside the floor polygon and outside every prop ellipse. */
export function clampPointAwayFromProps(
  pt: { x: number; y: number },
  poly: Array<{ x: number; y: number }>,
  props: IsometricPropDef[]
): { x: number; y: number } {
  let out = clampPointToPolygon(pt, poly);
  for (let pass = 0; pass < 2; pass++) {
    for (const prop of props) {
      if (!isPointInPropObstacle(out, prop)) continue;
      const { cx, cy, rx, ry } = getPropEllipse(prop);
      let dx = out.x - cx;
      let dy = out.y - cy;
      if (dx === 0 && dy === 0) dy = 1;
      const norm = Math.hypot(dx / rx, dy / ry) || 1;
      out = clampPointToPolygon(
        { x: cx + (dx / norm) * 1.12, y: cy + (dy / norm) * 1.12 },
        poly
      );
    }
  }
  return out;
}

/** True when segment A->B crosses through a non-walkable prop's core ground footprint. */
export function segmentIntersectsProp(
  a: { x: number; y: number },
  b: { x: number; y: number },
  prop: IsometricPropDef,
  scale = 0.92
): boolean {
  if (prop.walkable) return false;
  const { cx, cy, rx, ry } = getPropEllipse(prop);
  const ux = (a.x - cx) / (rx * scale);
  const uy = (a.y - cy) / (ry * scale);
  const vx = (b.x - a.x) / (rx * scale);
  const vy = (b.y - a.y) / (ry * scale);
  const vv = vx * vx + vy * vy || 1e-9;
  const t = Math.max(0, Math.min(1, -(ux * vx + uy * vy) / vv));
  const px = ux + t * vx;
  const py = uy + t * vy;
  return px * px + py * py < 1;
}

export function findNodePath(
  nodes: WalkNode[],
  fromId: string,
  toId: string
): Array<{ x: number; y: number; nodeId: string }> {
  const byId = new Map(nodes.map((n) => [n.id, n]));
  const start = byId.get(fromId);
  const goal = byId.get(toId);
  if (!start || !goal) return [];
  if (fromId === toId) return [{ x: goal.x, y: goal.y, nodeId: goal.id }];

  const queue: string[] = [fromId];
  const cameFrom = new Map<string, string | null>([[fromId, null]]);

  while (queue.length > 0) {
    const curr = queue.shift()!;
    if (curr === toId) break;
    const node = byId.get(curr);
    if (!node) continue;
    for (const nextId of node.neighbors) {
      if (!cameFrom.has(nextId)) {
        cameFrom.set(nextId, curr);
        queue.push(nextId);
      }
    }
  }

  if (!cameFrom.has(toId)) {
    return [{ x: goal.x, y: goal.y, nodeId: goal.id }];
  }

  const ids: string[] = [];
  let cursor: string | null = toId;
  while (cursor) {
    ids.unshift(cursor);
    cursor = cameFrom.get(cursor) ?? null;
  }

  return ids
    .slice(1)
    .map((id) => byId.get(id))
    .filter((n): n is WalkNode => Boolean(n))
    .map((n) => ({ x: n.x, y: n.y, nodeId: n.id }));
}

export function findNearestWalkNode(
  nodes: WalkNode[],
  pt: { x: number; y: number }
): WalkNode | undefined {
  let best: WalkNode | undefined;
  let bestDist = Infinity;
  for (const n of nodes) {
    const d = (n.x - pt.x) ** 2 + (n.y - pt.y) ** 2;
    if (d < bestDist) {
      bestDist = d;
      best = n;
    }
  }
  return best;
}

